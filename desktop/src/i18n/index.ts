export const DICTIONARIES: Record<Exclude<Locale, 'en'>, Record<string, string>> = { pl, uk };

let activeLocale: Locale = 'en';

export function setLocale(next: Locale): void {
  activeLocale = next;
}

export function getLocale(): Locale {
  return activeLocale;
}

/** Translate an English source string, with optional `{name}` placeholders. */
export function t(text: string, vars?: Record<string, string | number>): string {
  const template = activeLocale === 'en' ? text : DICTIONARIES[activeLocale]?.[text] ?? text;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

/** Locale-aware project count, including Polish and Ukrainian plurals. */
export function projectCount(count: number): string {
  if (activeLocale === 'en') return `${count} project${count === 1 ? '' : 's'}`;
  const mod10 = count % 10;
  const mod100 = count % 100;
  const few = mod10 >= 2 && mod10 <= 4 && !(mod100 >= 12 && mod100 <= 14);
  if (activeLocale === 'pl') return `${count} ${count === 1 ? 'projekt' : few ? 'projekty' : 'projektów'}`;
  return `${count} ${mod10 === 1 && mod100 !== 11 ? 'проєкт' : few ? 'проєкти' : 'проєктів'}`;
}

function plural(count: number, english: [string, string], polish: [string, string, string], ukrainian: [string, string, string]): string {
  if (activeLocale === 'en') return `${count} ${count === 1 ? english[0] : english[1]}`;
  const mod10 = count % 10;
  const mod100 = count % 100;
  const few = mod10 >= 2 && mod10 <= 4 && !(mod100 >= 12 && mod100 <= 14);
  if (activeLocale === 'pl') return `${count} ${count === 1 ? polish[0] : few ? polish[1] : polish[2]}`;
  return `${count} ${mod10 === 1 && mod100 !== 11 ? ukrainian[0] : few ? ukrainian[1] : ukrainian[2]}`;
}

/** Locale-aware scene count for project cards. */
export function sceneCount(count: number): string {
  return plural(count, ['scene', 'scenes'], ['scena', 'sceny', 'scen'], ['сцена', 'сцени', 'сцен']);
}

